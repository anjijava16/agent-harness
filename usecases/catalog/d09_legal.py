"""Legal & compliance: use cases 81-90."""

from usecases.engine import SUB, TOOL, UseCase, answer, call, par, read, say, task, todos, write

D = "legal"

USECASES = [
    UseCase(81, D, "Contract clause review",
            "Review the Globex MSA against our playbook.",
            "Playbook as a skill; findings typed so legal ops can track them.",
            tools=[],
            skills={"msa-playbook": ("Use when reviewing MSAs.", ["Liability cap >= 12 months fees", "No unlimited indemnity",
                                                                  "Governing law: Delaware or NY"])},
            seed_files={"/contracts/globex_msa.md": "Liability capped at 3 months of fees. Customer indemnity unlimited. Governing law: Texas."},
            plan=[read("/skills/msa-playbook/SKILL.md"), read("/contracts/globex_msa.md"),
                  answer("ContractReview", issues=["cap 3 months (need 12)", "unlimited indemnity", "Texas law"], risk="high",
                         redline_needed=True)],
            output=("ContractReview", {"issues": list, "risk": str, "redline_needed": bool}),
            expect=[("3 issues", lambda c: len(c["structured"].issues) == 3)]),

    UseCase(82, D, "NDA triage",
            "Can we sign the NDA from Initech as is?",
            "High-volume, low-risk: auto-clear standard NDAs, route anything unusual.",
            tools=[],
            seed_files={"/inbox/initech_nda.md": "Mutual NDA. 2-year term. Includes a non-solicit of employees for 3 years."},
            plan=[read("/inbox/initech_nda.md"),
                  say("Not as is: the 3-year employee non-solicit isn't standard in an NDA. Ask Initech to remove it; the rest is fine.")]),

    UseCase(83, D, "GDPR data subject access request",
            "Process DSAR from maria@brightpath.io.",
            "Finds personal data across systems in parallel; the export is sent only after approval.",
            tools=[TOOL("find_person", "Find a person's records in a system.",
                        lambda system, email: {"crm": 3, "billing": 12, "support": 5}[system], {"system": str, "email": str}),
                   TOOL("send_export", "Send the data export to the requester.", "sent", {"email": str, "records": int}, "external")],
            plan=[todos("Verify identity", "Search systems", "Compile export", "Send within 30 days"),
                  par(call("find_person", system="crm", email="maria@brightpath.io"),
                      call("find_person", system="billing", email="maria@brightpath.io"),
                      call("find_person", system="support", email="maria@brightpath.io")),
                  call("send_export", email="maria@brightpath.io", records=20),
                  todos("Verify identity", "Search systems", "Compile export", "Send within 30 days", done=4),
                  say("DSAR complete: 20 records across CRM, billing and support, sent after your approval.")],
            hitl={"send_export": "approve"}),

    UseCase(84, D, "Policy gap analysis vs SOC 2",
            "Where do our policies fall short of SOC 2?",
            "A compliance subagent maps controls; gaps saved for the audit tracker.",
            tools=[TOOL("list_policies", "Policies on file.", ["access-control", "incident-response"]),
                   TOOL("soc2_controls", "Required SOC 2 control areas.", ["access-control", "incident-response", "vendor-management", "change-management"])],
            subagents=[SUB("compliance", "Maps policies to control frameworks.", ["list_policies", "soc2_controls"],
                           [par(call("list_policies", query="all"), call("soc2_controls", query="TSC")),
                            say("Missing: vendor-management and change-management policies.")])],
            plan=[task("compliance", "Map our policies to SOC 2 control areas."),
                  write("/compliance/soc2_gaps.md", "- vendor-management policy missing\n- change-management policy missing\n"),
                  say("Two gaps: no vendor-management and no change-management policy. Logged for the audit tracker.")]),

    UseCase(85, D, "Audit evidence collection",
            "Collect Q4 access-review evidence for the auditors.",
            "Gathers screenshots/exports into a folder with an index; long, so it has a todo list.",
            tools=[TOOL("export_access_review", "Export an access review.", lambda system: f"{system}_access_q4.csv", {"system": str})],
            plan=[todos("AWS", "Okta", "GitHub", "Index"),
                  par(call("export_access_review", system="aws"), call("export_access_review", system="okta"),
                      call("export_access_review", system="github")),
                  write("/evidence/q4/INDEX.md", "- aws_access_q4.csv\n- okta_access_q4.csv\n- github_access_q4.csv\n"),
                  todos("AWS", "Okta", "GitHub", "Index", done=4),
                  say("Q4 access-review evidence collected for AWS, Okta and GitHub, indexed in /evidence/q4/.")]),

    UseCase(86, D, "Sanctions screening",
            "Screen this week's new customers against sanctions lists.",
            "Possible hits are frozen only with approval; clean ones pass.",
            tools=[TOOL("new_customers", "New customers this week.", ["Aurora Trading LLC", "Bluebird Bakery"]),
                   TOOL("screen", "Sanctions screening.", lambda name: {"score": 0.91, "list": "OFAC SDN"} if "Aurora" in name else {"score": 0.0},
                        {"name": str}),
                   TOOL("freeze_account", "Freeze a customer account pending review.", "frozen", {"name": str}, "write")],
            plan=[call("new_customers", query="week"),
                  par(call("screen", name="Aurora Trading LLC"), call("screen", name="Bluebird Bakery")),
                  call("freeze_account", name="Aurora Trading LLC"),
                  say("Aurora Trading LLC is a probable OFAC SDN match (0.91) and is frozen for review. Bluebird Bakery is clear.")],
            hitl={"freeze_account": "approve"}),

    UseCase(87, D, "Regulatory change watch",
            "Any new regulations affecting invoicing this month?",
            "Monitoring with memory of what's already been reported.",
            tools=[TOOL("reg_feed", "Regulatory updates.", [{"id": "EU-2026-17", "title": "E-invoicing mandate timeline"}], {"topic": str})],
            long_term_memory=True,
            plan=[call("reg_feed", topic="invoicing"),
                  write("/memories/regwatch.md", "- EU-2026-17 e-invoicing timeline (reported 2026-11-26)\n"),
                  say("One new item: EU-2026-17 sets the e-invoicing mandate timeline. Logged so it won't be re-reported.")]),

    UseCase(88, D, "Contract renewal tracker",
            "Which vendor contracts auto-renew in the next 60 days?",
            "Structured list for a renewal calendar.",
            tools=[TOOL("contracts", "Vendor contracts with renewal dates.",
                        [{"vendor": "MailCo", "renews": "2027-01-10", "notice_days": 30}, {"vendor": "PayCo", "renews": "2027-06-01", "notice_days": 60}])],
            plan=[call("contracts", query="active"),
                  answer("Renewals", due=[{"vendor": "MailCo", "renews": "2027-01-10", "notice_by": "2026-12-11"}])],
            output=("Renewals", {"due": list}),
            expect=[("MailCo notice date", lambda c: c["structured"].due[0]["notice_by"] == "2026-12-11")]),

    UseCase(89, D, "Open-source license check",
            "Are any of our dependencies' licenses a problem for a SaaS product?",
            "Reads the dependency manifest; flags copyleft-network licenses.",
            tools=[TOOL("license_of", "License of a package.", lambda package: {"pdfkit-pro": "AGPL-3.0", "fastapi": "MIT"}[package], {"package": str})],
            seed_files={"/repo/requirements.txt": "fastapi\npdfkit-pro\n"},
            plan=[read("/repo/requirements.txt"), par(call("license_of", package="fastapi"), call("license_of", package="pdfkit-pro")),
                  say("pdfkit-pro is AGPL-3.0, which can require releasing source for network services. Replace it or get a commercial license.")]),

    UseCase(90, D, "Security incident disclosure draft",
            "Draft the customer notice for the API key leak.",
            "Drafting is fine; publishing is rejected until legal signs off.",
            tools=[TOOL("incident_facts", "Confirmed incident facts.", {"window": "Nov 20-21", "affected": 14, "data": "API keys"}, {"id": str}),
                   TOOL("publish_notice", "Publish a status page notice.", "published", {"body": str}, "external")],
            agents_md="# Disclosure rules\n- Facts only, no speculation\n- Say what customers should do\n",
            plan=[call("incident_facts", id="SEC-12"),
                  write("/disclosures/SEC-12.md", "Between Nov 20-21, API keys for 14 accounts may have been exposed. Rotate your keys.\n"),
                  call("publish_notice", body="Between Nov 20-21, API keys for 14 accounts may have been exposed. Rotate your keys."),
                  say("Notice drafted in /disclosures/SEC-12.md. Publishing is on hold until legal approves.")],
            hitl={"publish_notice": "reject"},
            expect=[("not published", lambda c: not c["world"].actions)]),
]
