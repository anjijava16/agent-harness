    UseCase(61, D, "Resume screening against a rubric",
            "Screen the 3 applicants for the Senior Data Engineer role.",
            "Rubric in a skill; scores are typed; a guardrail blocks use of protected attributes.",
            tools=[TOOL("get_applicants", "Applicants for a role.",
                        [{"id": "A1", "years": 8, "skills": ["spark", "airflow"]}, {"id": "A2", "years": 3, "skills": ["sql"]},
                         {"id": "A3", "years": 6, "skills": ["spark", "dbt"]}], {"role": str}),
                   TOOL("lookup_profile", "Look up extra profile fields.", "n/a", {"applicant": str, "field": str})],
            skills={"de-rubric": ("Use when screening data engineers.", ["5+ years", "Spark required", "Orchestration a plus"])},
            plan=[read("/skills/de-rubric/SKILL.md"), call("get_applicants", role="senior-data-engineer"),
                  call("lookup_profile", applicant="A2", field="age"),
                  answer("Screening", advance=["A1", "A3"], decline=["A2"], basis="years and Spark per rubric")],
            guard={"lookup_profile": lambda a: "protected attribute" if a["field"] in {"age", "gender", "religion", "ethnicity"} else None},
            output=("Screening", {"advance": list, "decline": list, "basis": str}),
            expect=[("protected lookup blocked", lambda c: c["world"].blocked)]),

