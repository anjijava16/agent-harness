    UseCase(80, D, "Phishing report triage",
            "Triage the emails users reported as phishing today.",
            "Analysis subagent; quarantine needs approval; one report is a false positive.",
            tools=[TOOL("reported_emails", "User-reported emails.", [{"id": "r1", "from": "it-support@acme-secure.co"},
                                                                     {"id": "r2", "from": "noreply@stripe.com"}]),
                   TOOL("check_sender", "Sender reputation and auth results.", lambda sender: {"spf": "fail", "age_days": 2}
                        if "acme-secure" in sender else {"spf": "pass", "age_days": 4000}, {"sender": str}),
                   TOOL("quarantine", "Quarantine an email org-wide.", "quarantined", {"id": str}, "write")],
            subagents=[SUB("soc-analyst", "Analyzes suspicious emails.", ["check_sender"],
                           [par(call("check_sender", sender="it-support@acme-secure.co"), call("check_sender", sender="noreply@stripe.com")),
                            say("r1: SPF fail, 2-day-old look-alike domain -> phishing. r2: legitimate Stripe.")])],
            plan=[call("reported_emails", query="today"), task("soc-analyst", "Assess r1 and r2."),
                  call("quarantine", id="r1"),
                  say("r1 was phishing (look-alike domain, SPF fail) and is quarantined. r2 is a real Stripe email.")],
            hitl={"quarantine": "approve"}),
