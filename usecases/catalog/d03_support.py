"""Customer support: use cases 21-30."""

from usecases.engine import SUB, TOOL, UseCase, answer, call, par, read, say, task, write

D = "support"

USECASES = [
    UseCase(21, D, "Ticket triage to queues",
            "Route the unassigned support tickets.",
            "Structured output per batch, so routing code can trust the shape.",
            tools=[TOOL("list_unassigned", "Unassigned tickets.", [{"id": 1, "text": "Charged twice"}, {"id": 2, "text": "Can't log in"}])],
            plan=[call("list_unassigned", query="all"),
                  answer("Routing", billing=[1], auth=[2], other=[], urgent=[1])],
            output=("Routing", {"billing": list, "auth": list, "other": list, "urgent": list}),
            expect=[("double charge is urgent billing", lambda c: c["structured"].billing == [1] and c["structured"].urgent == [1])]),

    UseCase(22, D, "Refund request handling",
            "Handle ticket #4411: customer wants a refund for a late delivery.",
            "Policy lookup + refund; refunds over $100 need a supervisor, and the amount is edited down.",
            tools=[TOOL("get_order", "Fetch an order.", {"id": "O-77", "total": 240.0, "delivered_days_late": 6}, {"order_id": str}),
                   TOOL("issue_refund", "Refund an order.", "refunded", {"order_id": str, "amount": float}, "money")],
            skills={"refund-policy": ("Use for any refund.", ["Late > 5 days: refund shipping + 20%", "Never refund more than paid"])},
            plan=[read("/skills/refund-policy/SKILL.md"),
                  call("get_order", order_id="O-77"),
                  call("issue_refund", order_id="O-77", amount=240.0),
                  say("Refund issued for O-77 at the amount your supervisor approved ($48 = 20% for 6 days late).")],
            hitl={"issue_refund": ("edit", {"amount": 48.0})},
            expect=[("refund edited to policy amount", lambda c: c["world"].actions[0]["args"]["amount"] == 48.0)]),

    UseCase(23, D, "Knowledge-base answer with citations",
            "Answer: how do I export invoices to CSV?",
            "Search, read, answer with the article link; no guessing.",
            tools=[TOOL("search_kb", "Search help articles.", [{"id": "kb-12", "title": "Exporting invoices"}], {"query": str}),
                   TOOL("get_article", "Read a help article.", "Settings > Billing > Export > CSV. Max 10k rows.", {"id": str})],
            plan=[call("search_kb", query="export invoices CSV"), call("get_article", id="kb-12"),
                  say("Go to Settings > Billing > Export and pick CSV (up to 10k rows). Source: kb-12 'Exporting invoices'.")],
            expect=[("cites the article", lambda c: "kb-12" in c["final"])]),

    UseCase(24, D, "Escalation to engineering",
            "Ticket #4502 says the API returns 500 on every invoice create. Escalate properly.",
            "Reproduces, collects evidence, files one well-formed bug instead of a forwarded email.",
            tools=[TOOL("get_ticket", "Fetch a support ticket.", {"id": 4502, "account": "acme-co", "since": "08:10"}, {"id": int}),
                   TOOL("get_api_errors", "Recent API errors for an account.", {"endpoint": "POST /invoices", "status": 500, "count": 37}, {"account": str}),
                   TOOL("file_bug", "File a bug for engineering.", "BUG-902", {"title": str, "evidence": str, "severity": str}, "write")],
            plan=[call("get_ticket", id=4502), call("get_api_errors", account="acme-co"),
                  call("file_bug", title="POST /invoices 500 for acme-co since 08:10", evidence="37 errors in logs", severity="S2"),
                  say("Escalated as BUG-902 (S2) with 37 logged 500s. I told the customer we're on it.")],
            expect=[("bug filed", lambda c: c["world"].actions[0]["tool"] == "file_bug")]),

    UseCase(25, D, "Churn-risk outreach",
            "Reach out to accounts showing churn risk this week.",
            "A scoring subagent picks accounts; outreach emails are approved one by one (one rejected).",
            tools=[TOOL("get_usage_drops", "Accounts with big usage drops.",
                        [{"account": "Lumen", "drop": "-62%", "owner": "jo@lumen.io"}, {"account": "Tessa", "drop": "-41%", "owner": "ed@tessa.app"}]),
                   TOOL("send_email", "Send an email.", "sent", {"to": str, "subject": str, "body": str}, "external")],
            subagents=[SUB("churn-scorer", "Scores churn risk from usage data.", ["get_usage_drops"],
                           [call("get_usage_drops", query="7d"), say("High risk: Lumen (-62%). Medium: Tessa (-41%).")])],
            plan=[task("churn-scorer", "Who is at churn risk this week?"),
                  par(call("send_email", to="jo@lumen.io", subject="Checking in", body="Noticed less activity, can we help?"),
                      call("send_email", to="ed@tessa.app", subject="Checking in", body="Noticed less activity, can we help?")),
                  say("Reached out to Lumen. You held Tessa, which is already in renewal talks.")],
            hitl={"send_email": ["approve", "reject"]},
            expect=[("only Lumen contacted", lambda c: [a["args"]["to"] for a in c["world"].actions] == ["jo@lumen.io"])]),

    UseCase(26, D, "SLA breach watch",
            "Which tickets will breach SLA in the next 2 hours?",
            "Simple but valuable: computes deadlines, reassigns, and remembers who is overloaded.",
            tools=[TOOL("list_open_tickets", "Open tickets with SLA due times.",
                        [{"id": 7, "due_in_min": 45, "agent": "kim"}, {"id": 8, "due_in_min": 300, "agent": "lee"}]),
                   TOOL("reassign", "Reassign a ticket.", "reassigned", {"id": int, "to": str}, "write")],
            long_term_memory=True,
            plan=[call("list_open_tickets", query="open"), call("reassign", id=7, to="lee"),
                  write("/memories/load_notes.md", "- kim overloaded on 2026-11-26 afternoon\n"),
                  say("Ticket 7 would breach in 45 min; moved from kim to lee. Noted kim's load for next time.")],
            expect=[("reassigned and remembered", lambda c: c["world"].actions and "/load_notes.md" in c["store_keys"])]),

    UseCase(27, D, "Multilingual reply",
            "Reply to the Spanish-language ticket #6120 about a double charge.",
            "Translation is just another step; tone rules live in AGENTS.md.",
            tools=[TOOL("get_ticket", "Fetch a ticket.", {"id": 6120, "lang": "es", "text": "Me cobraron dos veces."}, {"id": int}),
                   TOOL("send_reply", "Reply on a ticket.", "replied", {"id": int, "body": str}, "external")],
            agents_md="# Support voice\n- Reply in the customer's language\n- Apologize once, then fix\n",
            plan=[call("get_ticket", id=6120),
                  call("send_reply", id=6120, body="Lo sentimos. Ya reembolsamos el cargo duplicado; lo verá en 3-5 días."),
                  say("Replied in Spanish: duplicate charge refunded, 3-5 days to appear.")],
            hitl={"send_reply": "approve"},
            expect=[("replied in Spanish", lambda c: "reembolsamos" in c["world"].actions[0]["args"]["body"])]),

    UseCase(28, D, "Warranty claim intake",
            "Process the warranty claim emailed in by Ravi Shah.",
            "Extracts fields from a messy email into a typed claim.",
            tools=[TOOL("get_email", "Fetch an email.", "Hi, my X200 (serial 99-1234, bought March 2026) stopped charging. Ravi", {"id": str})],
            plan=[call("get_email", id="m-889"),
                  answer("WarrantyClaim", customer="Ravi Shah", product="X200", serial="99-1234", purchase="2026-03",
                         issue="does not charge", in_warranty=True)],
            output=("WarrantyClaim", {"customer": str, "product": str, "serial": str, "purchase": str, "issue": str, "in_warranty": bool}),
            expect=[("serial extracted", lambda c: c["structured"].serial == "99-1234")]),

    UseCase(29, D, "Order status lookup",
            "Where is order O-5510?",
            "The everyday case: two lookups, one honest answer.",
            tools=[TOOL("get_order", "Fetch an order.", {"id": "O-5510", "carrier": "UPS", "tracking": "1Z999"}, {"order_id": str}),
                   TOOL("track_shipment", "Carrier tracking.", {"status": "Out for delivery", "eta": "today 6pm"}, {"tracking": str})],
            plan=[call("get_order", order_id="O-5510"), call("track_shipment", tracking="1Z999"),
                  say("O-5510 is out for delivery with UPS (1Z999), expected by 6pm today.")]),

    UseCase(30, D, "CSAT theme analysis",
            "What are customers unhappy about this month?",
            "Fan out over survey batches with a subagent, then write a themes report.",
            tools=[TOOL("get_csat_comments", "Low-score CSAT comments.", ["export is slow", "can't find invoice settings", "export timed out"],
                        {"month": str})],
            subagents=[SUB("theme-coder", "Groups free-text feedback into themes.", ["get_csat_comments"],
                           [call("get_csat_comments", month="2026-11"), say("Top themes: slow exports (2), settings hard to find (1).")])],
            plan=[task("theme-coder", "Code November's low CSAT comments into themes."),
                  write("/reports/csat_2026-11.md", "1. Export performance\n2. Settings discoverability\n"),
                  say("Main theme is slow or failing exports; second is finding invoice settings. Report saved.")],
            expect=[("report saved", lambda c: "/reports/csat_2026-11.md" in c["files"])]),
]
