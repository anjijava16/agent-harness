    UseCase(11, D, "Bug report triage",
            "Triage the new GitHub issues from last night.",
            "Label, dedupe and prioritize; filing labels is a write, so it's guarded to known labels only.",
            tools=[TOOL("list_new_issues", "New issues since a time.",
                        [{"n": 512, "title": "Crash on login with SSO"}, {"n": 513, "title": "Typo on pricing page"},
                         {"n": 514, "title": "SSO login crashes app"}], {"since": str}),
                   TOOL("search_issues", "Search existing issues.", [{"n": 512, "title": "Crash on login with SSO"}], {"query": str}),
                   TOOL("set_labels", "Set labels on an issue.", "labels set", {"n": int, "labels": list}, "write")],
            plan=[call("list_new_issues", since="yesterday 18:00"),
                  call("search_issues", query="SSO login crash"),
                  par(call("set_labels", n=512, labels=["bug", "P1", "auth"]), call("set_labels", n=513, labels=["docs", "P3"]),
                      call("set_labels", n=514, labels=["duplicate-of-512", "P1"])),
                  say("3 issues triaged: #512 P1 auth crash, #514 duplicate of #512, #513 P3 typo.")],
            guard={"set_labels": lambda a: None if all(l.split("-of-")[0] in {"bug", "docs", "P1", "P2", "P3", "auth", "duplicate"}
                                                       for l in a["labels"]) else "unknown label"},
            expect=[("three issues labelled", lambda c: len(c["world"].actions) == 3)]),

