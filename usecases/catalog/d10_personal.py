    UseCase(100, D, "Subscription audit",
            "Find subscriptions I'm not using and cancel them.",
            "Pulls card charges and usage; each cancellation is a separate approval (one kept).",
            tools=[TOOL("recurring_charges", "Recurring card charges.", [{"merchant": "StreamMax", "usd": 18}, {"merchant": "FitApp", "usd": 12},
                                                                          {"merchant": "CloudDrive", "usd": 10}]),
                   TOOL("last_used", "Days since last use.", lambda merchant: {"StreamMax": 3, "FitApp": 140, "CloudDrive": 95}[merchant],
                        {"merchant": str}),
                   TOOL("cancel_subscription", "Cancel a subscription.", "cancelled", {"merchant": str}, "write")],
            plan=[call("recurring_charges", query="card"),
                  par(call("last_used", merchant="StreamMax"), call("last_used", merchant="FitApp"), call("last_used", merchant="CloudDrive")),
                  par(call("cancel_subscription", merchant="FitApp"), call("cancel_subscription", merchant="CloudDrive")),
                  answer("SubscriptionAudit", cancelled=["FitApp"], kept=["StreamMax", "CloudDrive"], monthly_savings=12.0)],
            hitl={"cancel_subscription": ["approve", "reject"]},
            output=("SubscriptionAudit", {"cancelled": list, "kept": list, "monthly_savings": float}),
            expect=[("only FitApp cancelled", lambda c: [a["args"]["merchant"] for a in c["world"].actions] == ["FitApp"])]),
