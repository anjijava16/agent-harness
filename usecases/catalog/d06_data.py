"""Data & analytics: use cases 51-60."""

from usecases.engine import SUB, TOOL, UseCase, answer, call, par, read, say, task, todos, write

D = "data"

USECASES = [
    UseCase(51, D, "Natural-language SQL report",
            "What was revenue by region last quarter?",
            "Read-only SQL; a guardrail rejects anything that isn't a SELECT.",
            tools=[TOOL("run_sql", "Run a SQL query on the warehouse.",
                        lambda sql: [{"region": "NA", "rev": 1.9e6}, {"region": "EU", "rev": 1.1e6}] if sql.lower().startswith("select") else "error",
                        {"sql": str})],
            plan=[call("run_sql", sql="DELETE FROM revenue WHERE quarter='Q3'"),
                  call("run_sql", sql="SELECT region, SUM(amount) rev FROM revenue WHERE quarter='Q3' GROUP BY region"),
                  say("Q3 revenue: North America $1.9M, Europe $1.1M.")],
            guard={"run_sql": lambda a: None if a["sql"].strip().lower().startswith("select") else "only SELECT is allowed"},
            expect=[("DELETE blocked", lambda c: c["world"].blocked and "SELECT" in c["world"].blocked[0][1])]),

    UseCase(52, D, "Data quality check",
            "Check the customers table for quality issues.",
            "Runs checks in parallel and writes a report the data team can track.",
            tools=[TOOL("null_rate", "Null rate per column.", {"email": 0.03, "country": 0.21}, {"table": str}),
                   TOOL("duplicate_rate", "Duplicate rate on a key.", {"email": 0.012}, {"table": str, "key": str}),
                   TOOL("freshness", "Hours since last load.", {"hours": 30}, {"table": str})],
            plan=[par(call("null_rate", table="customers"), call("duplicate_rate", table="customers", key="email"),
                      call("freshness", table="customers")),
                  write("/dq/customers_2026-11-26.md", "- country 21% null (FAIL > 5%)\n- email dupes 1.2%\n- stale: 30h (SLA 24h)\n"),
                  say("Two failures: country is 21% null and the table is 30h stale (SLA 24h). Report saved.")]),

    UseCase(53, D, "KPI anomaly explanation",
            "Signups dropped 30% yesterday. Why?",
            "Breaks the metric down by dimension with a subagent and finds the culprit.",
            tools=[TOOL("metric_by_dim", "A metric broken down by a dimension.",
                        lambda dim: {"channel": {"paid": "-5%", "organic": "-2%", "referral": "-91%"}, "device": {"web": "-30%", "ios": "-29%"}}[dim],
                        {"dim": str})],
            subagents=[SUB("analyst", "Slices metrics by dimension to find drivers.", ["metric_by_dim"],
                           [par(call("metric_by_dim", dim="channel"), call("metric_by_dim", dim="device")),
                            say("Referral signups -91%; other channels flat. Device is not the driver.")])],
            plan=[task("analyst", "Find what drove yesterday's 30% signup drop."),
                  say("Referral signups fell 91%; everything else is flat. Check the referral partner's link or tracking.")]),

    UseCase(54, D, "A/B test readout",
            "Read out the pricing-page A/B test.",
            "Stats computed by a tool, decision typed, so nobody eyeballs p-values.",
            tools=[TOOL("ab_results", "A/B test results.", {"a": {"n": 5000, "conv": 0.041}, "b": {"n": 5000, "conv": 0.049}, "p": 0.008},
                        {"test": str})],
            plan=[call("ab_results", test="pricing-page-v2"),
                  answer("TestDecision", winner="B", lift=0.195, p_value=0.008, ship=True)],
            output=("TestDecision", {"winner": str, "lift": float, "p_value": float, "ship": bool})),

    UseCase(55, D, "Dashboard spec from a question",
            "I want a dashboard for collections health.",
            "Turns a vague ask into a concrete spec file with metrics and queries.",
            tools=[TOOL("list_tables", "Warehouse tables.", ["invoices", "payments", "customers"])],
            plan=[call("list_tables", query="finance"),
                  write("/dashboards/collections_health.yaml",
                        "metrics:\n  - dso\n  - overdue_amount\n  - pct_paid_on_time\nfilters: [region, segment]\n"),
                  say("Spec drafted with DSO, overdue amount and % paid on time, filterable by region and segment.")]),

    UseCase(56, D, "ETL failure triage",
            "The nightly payments ETL failed. Fix or escalate.",
            "Reads the error, retries once (allowed), escalates if it fails again.",
            tools=[TOOL("get_job_log", "Last job log.", "ERROR: source API returned 429 Too Many Requests", {"job": str}),
                   TOOL("rerun_job", "Rerun a job with backoff.", "succeeded on retry", {"job": str, "backoff_s": int}, "write")],
            plan=[call("get_job_log", job="payments_nightly"), call("rerun_job", job="payments_nightly", backoff_s=300),
                  say("Failure was a 429 from the source API. Reran with 5-min backoff and it succeeded; no escalation needed.")]),

    UseCase(57, D, "Cohort retention analysis",
            "How does retention differ for customers who used reminders in month 1?",
            "Two cohorts via SQL, insight in one sentence, chart spec saved.",
            tools=[TOOL("run_sql", "Run SQL.", lambda sql: {"m6_retention": 0.78 if "used_reminders" in sql else 0.61}, {"sql": str})],
            plan=[par(call("run_sql", sql="SELECT m6 FROM cohorts WHERE used_reminders"),
                      call("run_sql", sql="SELECT m6 FROM cohorts WHERE NOT reminder_user")),
                  write("/charts/retention_by_reminders.json", '{"type": "bar", "series": [0.78, 0.61]}'),
                  say("Customers who used reminders in month 1 retain 78% at month 6 vs 61% for others.")]),

    UseCase(58, D, "Revenue forecast",
            "Forecast next quarter's revenue.",
            "A modeling subagent does the math; the answer comes back typed with a range.",
            tools=[TOOL("monthly_revenue", "Monthly revenue history.", [1.0e6, 1.04e6, 1.09e6, 1.12e6, 1.18e6, 1.22e6])],
            subagents=[SUB("modeler", "Fits simple forecasting models.", ["monthly_revenue"],
                           [call("monthly_revenue", query="last 6 months"), say("~3.6%/month trend -> next quarter ~$3.92M (+/- 6%).")])],
            plan=[task("modeler", "Forecast next quarter from the last 6 months."),
                  answer("Forecast", point_usd=3.92e6, low_usd=3.68e6, high_usd=4.16e6, method="linear trend on 6 months")],
            output=("Forecast", {"point_usd": float, "low_usd": float, "high_usd": float, "method": str})),

    UseCase(59, D, "Schema documentation",
            "Document the payments schema for new analysts.",
            "Reads metadata, writes docs; house conventions from AGENTS.md.",
            tools=[TOOL("describe_table", "Columns and types.", {"payments": ["id uuid", "invoice_id uuid", "amount numeric", "paid_at timestamptz"]},
                        {"table": str})],
            agents_md="# Data docs\n- One line per column\n- Call out units and time zones\n",
            plan=[call("describe_table", table="payments"),
                  write("/docs/schema/payments.md", "- amount: numeric, US dollars (not cents)\n- paid_at: timestamptz, stored in UTC\n"),
                  say("payments documented; noted amount is in dollars and paid_at is UTC.")]),

    UseCase(60, D, "PII scan across tables",
            "Scan the warehouse for unmasked PII.",
            "Parallel scans; anything found is written to a restricted report, never echoed in chat.",
            tools=[TOOL("scan_table", "Detect PII patterns in a table sample.",
                        lambda table: {"support_tickets": ["email", "phone"], "events": []}.get(table, []), {"table": str})],
            plan=[par(call("scan_table", table="support_tickets"), call("scan_table", table="events")),
                  write("/restricted/pii_findings.md", "support_tickets: email, phone unmasked\n"),
                  say("Unmasked PII found in 1 table. Details are in /restricted/pii_findings.md (not repeated here).")]),
]
